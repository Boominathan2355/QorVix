// Real Vulkan compute backend. Compiled only when QORVIX_ENABLE_VULKAN is ON and the Vulkan loader
// + a GLSL->SPIR-V compiler were found (see vulkan/CMakeLists.txt). Provides the same facade as the
// CUDA backend so the CLI/tests drive either without #ifdefs.
//
// Design: correctness-first, headless-verifiable. All buffers are HOST_VISIBLE|HOST_COHERENT so a
// dispatch is upload -> record -> submit -> wait -> read with no staging; this runs identically on
// Mesa's software device (lavapipe) — where the argmax-parity gate is checked with no physical GPU
// — and on real NVIDIA/AMD/Apple/Intel hardware (device-local + staging is a later throughput
// milestone, not a correctness one). The compute shaders are SPIR-V embedded at build time.
#include "qorvix/vulkan/backend.hpp"

