// fp16 (IEEE half) <-> float, matching the GGUF scale encoding the shader decodes with
// unpackHalf2x16. Kept on the host so the reference and the shader agree bit-for-bit on the scale.
float decodeHalf(std::uint16_t h) {
  const std::uint32_t sign = (h & 0x8000u) << 16;
  const std::uint32_t exp = (h >> 10) & 0x1F;
  const std::uint32_t mant = h & 0x3FF;
  std::uint32_t bits;
  if (exp == 0) {
    if (mant == 0) {
      bits = sign;  // +/- zero
    } else {
      // subnormal half -> normalized float
      int e = -1;
      std::uint32_t m = mant;
      do {
        m <<= 1;
        ++e;
      } while ((m & 0x400u) == 0);
      m &= 0x3FFu;
      bits = sign | ((127 - 15 - e) << 23) | (m << 13);
    }
  } else if (exp == 0x1F) {
    bits = sign | 0x7F800000u | (mant << 13);  // inf/nan
  } else {
    bits = sign | ((exp - 15 + 127) << 23) | (mant << 13);
  }
  float f;
  std::memcpy(&f, &bits, 4);
  return f;
}

std::uint16_t encodeHalf(float f) {
  std::uint32_t x;
  std::memcpy(&x, &f, 4);
  const std::uint32_t sign = (x >> 16) & 0x8000u;
  std::int32_t exp = static_cast<std::int32_t>((x >> 23) & 0xFF) - 127 + 15;
  std::uint32_t mant = x & 0x7FFFFFu;
  if (exp <= 0) return static_cast<std::uint16_t>(sign);          // flush tiny to zero (sufficient here)
  if (exp >= 0x1F) return static_cast<std::uint16_t>(sign | 0x7C00u);  // overflow -> inf
  return static_cast<std::uint16_t>(sign | (exp << 10) | (mant >> 13));
}

// 6-bit (scale, min) unpack for sub-block j of a Q4_K scales array — the host mirror of the
// shader's getScaleMinK4 (verbatim from ggml), so the reference and the shader agree.
void getScaleMinK4(int j, const std::uint8_t* q, unsigned char& d, unsigned char& m) {
  if (j < 4) {
    d = q[j] & 63;
    m = q[j + 4] & 63;
  } else {
    d = (q[j + 4] & 0xF) | ((q[j - 4] >> 6) << 4);
    m = (q[j + 4] >> 4) | ((q[j] >> 6) << 4);
  }
}

// ---- minimal Vulkan compute context ---------------------------------------------------------
struct Context {
  VkInstance instance = VK_NULL_HANDLE;
  VkPhysicalDevice phys = VK_NULL_HANDLE;
  VkDevice device = VK_NULL_HANDLE;
  VkQueue queue = VK_NULL_HANDLE;
  std::uint32_t queueFamily = 0;
  VkCommandPool pool = VK_NULL_HANDLE;
  VkPhysicalDeviceMemoryProperties memProps{};
  bool ok = false;

  ~Context() {
    if (device) {
      if (pool) vkDestroyCommandPool(device, pool, nullptr);
      vkDestroyDevice(device, nullptr);
    }
    if (instance) vkDestroyInstance(instance, nullptr);
  }
};

// Pick a queue family that supports compute.
bool findComputeQueue(VkPhysicalDevice phys, std::uint32_t& family) {
  std::uint32_t n = 0;
  vkGetPhysicalDeviceQueueFamilyProperties(phys, &n, nullptr);
  std::vector<VkQueueFamilyProperties> qf(n);
  vkGetPhysicalDeviceQueueFamilyProperties(phys, &n, qf.data());
  for (std::uint32_t i = 0; i < n; ++i) {
    if (qf[i].queueFlags & VK_QUEUE_COMPUTE_BIT) {
      family = i;
      return true;
    }
  }
  return false;
}

// Prefer a discrete GPU, then integrated, then anything (incl. the CPU software device).
VkPhysicalDevice pickPhysical(VkInstance inst) {
  std::uint32_t n = 0;
  vkEnumeratePhysicalDevices(inst, &n, nullptr);
  if (n == 0) return VK_NULL_HANDLE;
  std::vector<VkPhysicalDevice> devs(n);
  vkEnumeratePhysicalDevices(inst, &n, devs.data());
  VkPhysicalDevice best = VK_NULL_HANDLE;
  int bestRank = -1;
  for (auto d : devs) {
    VkPhysicalDeviceProperties p{};
    vkGetPhysicalDeviceProperties(d, &p);
    int rank = 0;
    switch (p.deviceType) {
      case VK_PHYSICAL_DEVICE_TYPE_DISCRETE_GPU: rank = 4; break;
      case VK_PHYSICAL_DEVICE_TYPE_INTEGRATED_GPU: rank = 3; break;
      case VK_PHYSICAL_DEVICE_TYPE_VIRTUAL_GPU: rank = 2; break;
      case VK_PHYSICAL_DEVICE_TYPE_CPU: rank = 1; break;
      default: rank = 0; break;
    }
    std::uint32_t fam = 0;
    if (rank > bestRank && findComputeQueue(d, fam)) {
      best = d;
      bestRank = rank;
    }
  }
  return best;
}

Context makeContext() {
  Context c;
  VkApplicationInfo app{};
  app.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO;
  app.pApplicationName = "qorvix";
  app.apiVersion = VK_API_VERSION_1_1;

  VkInstanceCreateInfo ici{};
  ici.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO;
  ici.pApplicationInfo = &app;
  if (vkCreateInstance(&ici, nullptr, &c.instance) != VK_SUCCESS) return c;

  c.phys = pickPhysical(c.instance);
  if (!c.phys) return c;
  if (!findComputeQueue(c.phys, c.queueFamily)) return c;
  vkGetPhysicalDeviceMemoryProperties(c.phys, &c.memProps);

  const float prio = 1.0f;
  VkDeviceQueueCreateInfo qci{};
  qci.sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO;
  qci.queueFamilyIndex = c.queueFamily;
  qci.queueCount = 1;
  qci.pQueuePriorities = &prio;

  VkDeviceCreateInfo dci{};
  dci.sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO;
  dci.queueCreateInfoCount = 1;
  dci.pQueueCreateInfos = &qci;
  if (vkCreateDevice(c.phys, &dci, nullptr, &c.device) != VK_SUCCESS) return c;
  vkGetDeviceQueue(c.device, c.queueFamily, 0, &c.queue);

  VkCommandPoolCreateInfo pci{};
  pci.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
  pci.queueFamilyIndex = c.queueFamily;
  if (vkCreateCommandPool(c.device, &pci, nullptr, &c.pool) != VK_SUCCESS) return c;

  c.ok = true;
  return c;
}

std::uint32_t findMemType(const Context& c, std::uint32_t typeBits, VkMemoryPropertyFlags want) {
  for (std::uint32_t i = 0; i < c.memProps.memoryTypeCount; ++i) {
    if ((typeBits & (1u << i)) && (c.memProps.memoryTypes[i].propertyFlags & want) == want) return i;
  }
  return UINT32_MAX;
}

// A host-visible, coherent storage buffer. Correctness-first: no staging, map/unmap directly.
struct Buffer {
  VkDevice device = VK_NULL_HANDLE;
  VkBuffer buf = VK_NULL_HANDLE;
  VkDeviceMemory mem = VK_NULL_HANDLE;
  VkDeviceSize size = 0;

  void destroy() {
    if (buf) vkDestroyBuffer(device, buf, nullptr);
    if (mem) vkFreeMemory(device, mem, nullptr);
    buf = VK_NULL_HANDLE;
    mem = VK_NULL_HANDLE;
  }
};

bool makeBuffer(const Context& c, VkDeviceSize size, Buffer& out) {
  out.device = c.device;
  out.size = size;
  VkBufferCreateInfo bci{};
  bci.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
  bci.size = size;
  bci.usage = VK_BUFFER_USAGE_STORAGE_BUFFER_BIT;
  bci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
  if (vkCreateBuffer(c.device, &bci, nullptr, &out.buf) != VK_SUCCESS) return false;

  VkMemoryRequirements req{};
  vkGetBufferMemoryRequirements(c.device, out.buf, &req);
  const std::uint32_t mt = findMemType(
      c, req.memoryTypeBits, VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
  if (mt == UINT32_MAX) return false;

  VkMemoryAllocateInfo mai{};
  mai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
  mai.allocationSize = req.size;
  mai.memoryTypeIndex = mt;
  if (vkAllocateMemory(c.device, &mai, nullptr, &out.mem) != VK_SUCCESS) return false;
  return vkBindBufferMemory(c.device, out.buf, out.mem, 0) == VK_SUCCESS;
}

bool upload(const Buffer& b, const void* src, VkDeviceSize n) {
  void* p = nullptr;
  if (vkMapMemory(b.device, b.mem, 0, n, 0, &p) != VK_SUCCESS) return false;
  std::memcpy(p, src, n);
  vkUnmapMemory(b.device, b.mem);
  return true;
}

bool download(const Buffer& b, void* dst, VkDeviceSize n) {
  void* p = nullptr;
  if (vkMapMemory(b.device, b.mem, 0, n, 0, &p) != VK_SUCCESS) return false;
  std::memcpy(dst, p, n);
  vkUnmapMemory(b.device, b.mem);
  return true;
}

// One-shot compute pipeline over N storage-buffer bindings with a push-constant block. Builds the
// pipeline, dispatches `groups` workgroups, and waits. Returns false on any Vulkan error.
bool dispatch(const Context& c, const std::uint32_t* spirv, std::size_t spirvBytes,
              const std::vector<VkBuffer>& buffers, const void* push, std::uint32_t pushSize,
              std::uint32_t groups) {
  const std::uint32_t nb = static_cast<std::uint32_t>(buffers.size());

  std::vector<VkDescriptorSetLayoutBinding> binds(nb);
  for (std::uint32_t i = 0; i < nb; ++i) {
    binds[i] = {i, VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, 1, VK_SHADER_STAGE_COMPUTE_BIT, nullptr};
  }
  VkDescriptorSetLayoutCreateInfo dslci{};
  dslci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
  dslci.bindingCount = nb;
  dslci.pBindings = binds.data();
  VkDescriptorSetLayout dsl = VK_NULL_HANDLE;
  if (vkCreateDescriptorSetLayout(c.device, &dslci, nullptr, &dsl) != VK_SUCCESS) return false;

  VkPushConstantRange pcr{VK_SHADER_STAGE_COMPUTE_BIT, 0, pushSize};
  VkPipelineLayoutCreateInfo plci{};
  plci.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
  plci.setLayoutCount = 1;
  plci.pSetLayouts = &dsl;
  plci.pushConstantRangeCount = pushSize ? 1 : 0;
  plci.pPushConstantRanges = pushSize ? &pcr : nullptr;
  VkPipelineLayout layout = VK_NULL_HANDLE;
  if (vkCreatePipelineLayout(c.device, &plci, nullptr, &layout) != VK_SUCCESS) {
    vkDestroyDescriptorSetLayout(c.device, dsl, nullptr);
    return false;
  }

  VkShaderModuleCreateInfo smci{};
  smci.sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO;
  smci.codeSize = spirvBytes;
  smci.pCode = spirv;
  VkShaderModule shader = VK_NULL_HANDLE;
  bool okAll = false;
  VkPipeline pipe = VK_NULL_HANDLE;
  VkDescriptorPool descPool = VK_NULL_HANDLE;
  VkCommandBuffer cmd = VK_NULL_HANDLE;
  VkFence fence = VK_NULL_HANDLE;
  do {
    if (vkCreateShaderModule(c.device, &smci, nullptr, &shader) != VK_SUCCESS) break;

    VkPipelineShaderStageCreateInfo stage{};
    stage.sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO;
    stage.stage = VK_SHADER_STAGE_COMPUTE_BIT;
    stage.module = shader;
    stage.pName = "main";
    VkComputePipelineCreateInfo cpci{};
    cpci.sType = VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO;
    cpci.stage = stage;
    cpci.layout = layout;
    if (vkCreateComputePipelines(c.device, VK_NULL_HANDLE, 1, &cpci, nullptr, &pipe) != VK_SUCCESS)
      break;

    VkDescriptorPoolSize ps{VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, nb};
    VkDescriptorPoolCreateInfo dpci{};
    dpci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
    dpci.maxSets = 1;
    dpci.poolSizeCount = 1;
    dpci.pPoolSizes = &ps;
    if (vkCreateDescriptorPool(c.device, &dpci, nullptr, &descPool) != VK_SUCCESS) break;

    VkDescriptorSetAllocateInfo dsai{};
    dsai.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
    dsai.descriptorPool = descPool;
    dsai.descriptorSetCount = 1;
    dsai.pSetLayouts = &dsl;
    VkDescriptorSet set = VK_NULL_HANDLE;
    if (vkAllocateDescriptorSets(c.device, &dsai, &set) != VK_SUCCESS) break;

    std::vector<VkDescriptorBufferInfo> dbi(nb);
    std::vector<VkWriteDescriptorSet> writes(nb);
    for (std::uint32_t i = 0; i < nb; ++i) {
      dbi[i] = {buffers[i], 0, VK_WHOLE_SIZE};
      writes[i] = {};
      writes[i].sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET;
      writes[i].dstSet = set;
      writes[i].dstBinding = i;
      writes[i].descriptorCount = 1;
      writes[i].descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER;
      writes[i].pBufferInfo = &dbi[i];
    }
    vkUpdateDescriptorSets(c.device, nb, writes.data(), 0, nullptr);

    VkCommandBufferAllocateInfo cbai{};
    cbai.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
    cbai.commandPool = c.pool;
    cbai.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
    cbai.commandBufferCount = 1;
    if (vkAllocateCommandBuffers(c.device, &cbai, &cmd) != VK_SUCCESS) break;

    VkCommandBufferBeginInfo bi{};
    bi.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
    bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
    vkBeginCommandBuffer(cmd, &bi);
    vkCmdBindPipeline(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, pipe);
    vkCmdBindDescriptorSets(cmd, VK_PIPELINE_BIND_POINT_COMPUTE, layout, 0, 1, &set, 0, nullptr);
    if (pushSize) vkCmdPushConstants(cmd, layout, VK_SHADER_STAGE_COMPUTE_BIT, 0, pushSize, push);
    vkCmdDispatch(cmd, groups, 1, 1);
    vkEndCommandBuffer(cmd);

    VkFenceCreateInfo fci{};
    fci.sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO;
    if (vkCreateFence(c.device, &fci, nullptr, &fence) != VK_SUCCESS) break;
    VkSubmitInfo si{};
    si.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
    si.commandBufferCount = 1;
    si.pCommandBuffers = &cmd;
    if (vkQueueSubmit(c.queue, 1, &si, fence) != VK_SUCCESS) break;
    if (vkWaitForFences(c.device, 1, &fence, VK_TRUE, UINT64_MAX) != VK_SUCCESS) break;
    okAll = true;
  } while (false);

  if (fence) vkDestroyFence(c.device, fence, nullptr);
  if (cmd) vkFreeCommandBuffers(c.device, c.pool, 1, &cmd);
  if (descPool) vkDestroyDescriptorPool(c.device, descPool, nullptr);
  if (pipe) vkDestroyPipeline(c.device, pipe, nullptr);
  if (shader) vkDestroyShaderModule(c.device, shader, nullptr);
  vkDestroyPipelineLayout(c.device, layout, nullptr);
  vkDestroyDescriptorSetLayout(c.device, dsl, nullptr);
  return okAll;
}

