int deviceCount() {
  Context c = makeContext();
  return c.ok ? 1 : 0;  // one usable compute device (best pick); enumerateDevices() lists all
}

std::vector<DeviceInfo> enumerateDevices() {
  std::vector<DeviceInfo> out;
  VkApplicationInfo app{};
  app.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO;
  app.apiVersion = VK_API_VERSION_1_1;
  VkInstanceCreateInfo ici{};
  ici.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO;
  ici.pApplicationInfo = &app;
  VkInstance inst = VK_NULL_HANDLE;
  if (vkCreateInstance(&ici, nullptr, &inst) != VK_SUCCESS) return out;

  std::uint32_t n = 0;
  vkEnumeratePhysicalDevices(inst, &n, nullptr);
  std::vector<VkPhysicalDevice> devs(n);
  vkEnumeratePhysicalDevices(inst, &n, devs.data());
  for (std::uint32_t i = 0; i < n; ++i) {
    VkPhysicalDeviceProperties p{};
    vkGetPhysicalDeviceProperties(devs[i], &p);
    VkPhysicalDeviceMemoryProperties mp{};
    vkGetPhysicalDeviceMemoryProperties(devs[i], &mp);
    std::size_t local = 0;
    for (std::uint32_t h = 0; h < mp.memoryHeapCount; ++h) {
      if (mp.memoryHeaps[h].flags & VK_MEMORY_HEAP_DEVICE_LOCAL_BIT)
        local = std::max<std::size_t>(local, mp.memoryHeaps[h].size);
    }
    DeviceInfo d;
    d.index = static_cast<int>(i);
    d.name = p.deviceName;
    d.apiVersion = p.apiVersion;
    d.vendorID = p.vendorID;
    d.deviceID = p.deviceID;
    d.deviceType = static_cast<int>(p.deviceType);
    d.deviceLocalMem = local;
    out.push_back(std::move(d));
  }
  vkDestroyInstance(inst, nullptr);
  return out;
}

std::optional<DeviceInfo> deviceInfo(int index) {
  auto all = enumerateDevices();
  for (auto& d : all)
    if (d.index == index) return d;
  return std::nullopt;
}

SelfTestResult selfTest() {
  Context c = makeContext();
  if (!c.ok) return {false, false, "no Vulkan device present"};

  VkPhysicalDeviceProperties p{};
  vkGetPhysicalDeviceProperties(c.phys, &p);

  // Bring-up: a trivial Q8_0 dispatch that must reproduce a hand-computed value. This exercises the
  // whole path — instance, device, queue, buffers, descriptors, pipeline, submit, readback — so a
  // green result means the compute plumbing works, not just that a device enumerated.
  const int rows = 1, cols = 32;
  std::vector<std::uint8_t> W(34, 0);
  const std::uint16_t hs = encodeHalf(0.5f);
  W[0] = static_cast<std::uint8_t>(hs & 0xFF);
  W[1] = static_cast<std::uint8_t>(hs >> 8);
  const float d = decodeHalf(hs);
  std::vector<float> x(cols), ref(rows, 0.0f);
  double acc = 0.0;
  for (int i = 0; i < cols; ++i) {
    const signed char q = static_cast<signed char>((i % 5) - 2);
    W[2 + i] = static_cast<std::uint8_t>(q);
    x[i] = 0.25f * ((i % 7) - 3);
    acc += d * static_cast<float>(q) * x[i];
  }
  ref[0] = static_cast<float>(acc);

  const VkDeviceSize wBytes = (W.size() + 3) & ~VkDeviceSize(3);  // pad to 4 for the uint[] SSBO
  Buffer bw{}, bx{}, bo{};
  if (!makeBuffer(c, wBytes, bw) || !makeBuffer(c, cols * sizeof(float), bx) ||
      !makeBuffer(c, rows * sizeof(float), bo)) {
    bw.destroy();
    bx.destroy();
    bo.destroy();
    return {true, false, "buffer allocation failed"};
  }
  upload(bw, W.data(), W.size());
  upload(bx, x.data(), cols * sizeof(float));
  struct {
    std::uint32_t rows, cols;
  } pc{static_cast<std::uint32_t>(rows), static_cast<std::uint32_t>(cols)};
  const std::uint32_t groups = (rows + 63) / 64;
  const bool ran = dispatch(c, qmatmul_q8_0_spv, sizeof(qmatmul_q8_0_spv), {bw.buf, bx.buf, bo.buf},
                            &pc, sizeof(pc), groups);
  std::vector<float> got(rows, 0.0f);
  if (ran) download(bo, got.data(), rows * sizeof(float));
  bw.destroy();
  bx.destroy();
  bo.destroy();
  if (!ran) return {true, false, "compute dispatch failed"};

  const float err = std::fabs(got[0] - ref[0]);
  if (err > 1e-3f)
    return {true, false, "compute result disagrees with host reference (err " + std::to_string(err) + ")"};
  return {true, true, std::string("compute pipeline OK on ") + p.deviceName};
}

SelfTestResult qmatmulQ8_0SelfTest() {
  Context c = makeContext();
  if (!c.ok) return {false, false, "no Vulkan device present"};
  VkPhysicalDeviceProperties dp{};
  vkGetPhysicalDeviceProperties(c.phys, &dp);

  // ---- correctness on a small Q8_0 matrix vs a host reference (mirrors the CUDA self-test) ----
  const int rows = 64, cols = 256;
  const int nBlocks = cols / 32;
  const std::size_t rowBytes = static_cast<std::size_t>(nBlocks) * 34;
  std::vector<std::uint8_t> W(static_cast<std::size_t>(rows) * rowBytes, 0);
  std::vector<float> x(cols), ref(rows, 0.0f), got(rows, 0.0f);
  for (int i = 0; i < cols; ++i) x[i] = 0.1f * ((i % 5) - 2);
  for (int r = 0; r < rows; ++r) {
    double acc = 0.0;
    for (int b = 0; b < nBlocks; ++b) {
      std::uint8_t* blk = W.data() + static_cast<std::size_t>(r) * rowBytes + static_cast<std::size_t>(b) * 34;
      const std::uint16_t hs = encodeHalf(0.02f * ((r % 7) + 1));
      blk[0] = static_cast<std::uint8_t>(hs & 0xFF);
      blk[1] = static_cast<std::uint8_t>(hs >> 8);
      const float d = decodeHalf(hs);  // rounded scale so the reference matches the shader
      for (int i = 0; i < 32; ++i) {
        const signed char q = static_cast<signed char>(((r + b + i) % 15) - 7);
        blk[2 + i] = static_cast<std::uint8_t>(q);
        acc += d * static_cast<float>(q) * x[b * 32 + i];
      }
    }
    ref[r] = static_cast<float>(acc);
  }

  const VkDeviceSize wBytes = (W.size() + 3) & ~VkDeviceSize(3);
  Buffer bw{}, bx{}, bo{};
  if (!makeBuffer(c, wBytes, bw) || !makeBuffer(c, cols * sizeof(float), bx) ||
      !makeBuffer(c, rows * sizeof(float), bo)) {
    bw.destroy();
    bx.destroy();
    bo.destroy();
    return {true, false, "buffer allocation failed"};
  }
  upload(bw, W.data(), W.size());
  upload(bx, x.data(), cols * sizeof(float));
  struct {
    std::uint32_t rows, cols;
  } pc{static_cast<std::uint32_t>(rows), static_cast<std::uint32_t>(cols)};
  const bool ran = dispatch(c, qmatmul_q8_0_spv, sizeof(qmatmul_q8_0_spv), {bw.buf, bx.buf, bo.buf},
                            &pc, sizeof(pc), (rows + 63) / 64);
  if (ran) download(bo, got.data(), rows * sizeof(float));
  bw.destroy();
  bx.destroy();
  bo.destroy();
  if (!ran) return {true, false, "qmatmul dispatch failed"};

  float maxErr = 0.0f;
  for (int r = 0; r < rows; ++r) maxErr = std::max(maxErr, std::fabs(got[r] - ref[r]));
  if (maxErr > 1e-2f)
    return {true, false, "Vulkan qmatmul disagrees with host reference (max err " +
                             std::to_string(maxErr) + ")"};

  return {true, true, std::string("Vulkan Q8_0 matmul matches host reference (max err ") +
                          std::to_string(maxErr) + ") on " + dp.deviceName};
}

