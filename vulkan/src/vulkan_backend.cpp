int deviceCount() {
  Context c = makeContext();
  return c.ok ? 1 : 0;  // one usable compute device (best pick); enumerateDevices() lists all
}

std::vector<DeviceInfo> enumerateDevices() {
  std::vector<DeviceInfo> out;
  VkApplicationInfo app{};
  app.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO;
  app.apiVersion = VK_API_VERSION_1_1;
  VkInstanceCreateInfo ici{};
  ici.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO;
  ici.pApplicationInfo = &app;
  VkInstance inst = VK_NULL_HANDLE;
  if (vkCreateInstance(&ici, nullptr, &inst) != VK_SUCCESS) return out;

  std::uint32_t n = 0;
  vkEnumeratePhysicalDevices(inst, &n, nullptr);
  std::vector<VkPhysicalDevice> devs(n);
  vkEnumeratePhysicalDevices(inst, &n, devs.data());
  for (std::uint32_t i = 0; i < n; ++i) {
    VkPhysicalDeviceProperties p{};
    vkGetPhysicalDeviceProperties(devs[i], &p);
    VkPhysicalDeviceMemoryProperties mp{};
    vkGetPhysicalDeviceMemoryProperties(devs[i], &mp);
    std::size_t local = 0;
    for (std::uint32_t h = 0; h < mp.memoryHeapCount; ++h) {
      if (mp.memoryHeaps[h].flags & VK_MEMORY_HEAP_DEVICE_LOCAL_BIT)
        local = std::max<std::size_t>(local, mp.memoryHeaps[h].size);
    }
    DeviceInfo d;
    d.index = static_cast<int>(i);
    d.name = p.deviceName;
    d.apiVersion = p.apiVersion;
    d.vendorID = p.vendorID;
    d.deviceID = p.deviceID;
    d.deviceType = static_cast<int>(p.deviceType);
    d.deviceLocalMem = local;
    out.push_back(std::move(d));
  }
  vkDestroyInstance(inst, nullptr);
  return out;
}

std::optional<DeviceInfo> deviceInfo(int index) {
  auto all = enumerateDevices();
  for (auto& d : all)
    if (d.index == index) return d;
  return std::nullopt;
}

SelfTestResult selfTest() {
  Context c = makeContext();
  if (!c.ok) return {false, false, "no Vulkan device present"};

  VkPhysicalDeviceProperties p{};
  vkGetPhysicalDeviceProperties(c.phys, &p);

  // Bring-up: a trivial Q8_0 dispatch that must reproduce a hand-computed value. This exercises the
  // whole path — instance, device, queue, buffers, descriptors, pipeline, submit, readback — so a
  // green result means the compute plumbing works, not just that a device enumerated.
  const int rows = 1, cols = 32;
  std::vector<std::uint8_t> W(34, 0);
  const std::uint16_t hs = encodeHalf(0.5f);
  W[0] = static_cast<std::uint8_t>(hs & 0xFF);
  W[1] = static_cast<std::uint8_t>(hs >> 8);
  const float d = decodeHalf(hs);
  std::vector<float> x(cols), ref(rows, 0.0f);
  double acc = 0.0;
  for (int i = 0; i < cols; ++i) {
    const signed char q = static_cast<signed char>((i % 5) - 2);
    W[2 + i] = static_cast<std::uint8_t>(q);
    x[i] = 0.25f * ((i % 7) - 3);
    acc += d * static_cast<float>(q) * x[i];
  }
  ref[0] = static_cast<float>(acc);

  const VkDeviceSize wBytes = (W.size() + 3) & ~VkDeviceSize(3);  // pad to 4 for the uint[] SSBO
  Buffer bw{}, bx{}, bo{};
  if (!makeBuffer(c, wBytes, bw) || !makeBuffer(c, cols * sizeof(float), bx) ||
      !makeBuffer(c, rows * sizeof(float), bo)) {
    bw.destroy();
    bx.destroy();
    bo.destroy();
    return {true, false, "buffer allocation failed"};
  }
  upload(bw, W.data(), W.size());
  upload(bx, x.data(), cols * sizeof(float));
  struct {
    std::uint32_t rows, cols;
  } pc{static_cast<std::uint32_t>(rows), static_cast<std::uint32_t>(cols)};
  const std::uint32_t groups = (rows + 63) / 64;
  const bool ran = dispatch(c, qmatmul_q8_0_spv, sizeof(qmatmul_q8_0_spv), {bw.buf, bx.buf, bo.buf},
                            &pc, sizeof(pc), groups);
  std::vector<float> got(rows, 0.0f);
  if (ran) download(bo, got.data(), rows * sizeof(float));
  bw.destroy();
  bx.destroy();
  bo.destroy();
  if (!ran) return {true, false, "compute dispatch failed"};

  const float err = std::fabs(got[0] - ref[0]);
  if (err > 1e-3f)
    return {true, false, "compute result disagrees with host reference (err " + std::to_string(err) + ")"};
  return {true, true, std::string("compute pipeline OK on ") + p.deviceName};
}

SelfTestResult qmatmulQ8_0SelfTest() {
  Context c = makeContext();
  if (!c.ok) return {false, false, "no Vulkan device present"};
  VkPhysicalDeviceProperties dp{};
  vkGetPhysicalDeviceProperties(c.phys, &dp);

  // ---- correctness on a small Q8_0 matrix vs a host reference (mirrors the CUDA self-test) ----
  const int rows = 64, cols = 256;
  const int nBlocks = cols / 32;
  const std::size_t rowBytes = static_cast<std::size_t>(nBlocks) * 34;
  std::vector<std::uint8_t> W(static_cast<std::size_t>(rows) * rowBytes, 0);
  std::vector<float> x(cols), ref(rows, 0.0f), got(rows, 0.0f);
  for (int i = 0; i < cols; ++i) x[i] = 0.1f * ((i % 5) - 2);
  for (int r = 0; r < rows; ++r) {
    double acc = 0.0;
    for (int b = 0; b < nBlocks; ++b) {
      std::uint8_t* blk = W.data() + static_cast<std::size_t>(r) * rowBytes + static_cast<std::size_t>(b) * 34;
      const std::uint16_t hs = encodeHalf(0.02f * ((r % 7) + 1));
      blk[0] = static_cast<std::uint8_t>(hs & 0xFF);
      blk[1] = static_cast<std::uint8_t>(hs >> 8);
      const float d = decodeHalf(hs);  // rounded scale so the reference matches the shader
      for (int i = 0; i < 32; ++i) {
        const signed char q = static_cast<signed char>(((r + b + i) % 15) - 7);
        blk[2 + i] = static_cast<std::uint8_t>(q);
        acc += d * static_cast<float>(q) * x[b * 32 + i];
      }
    }
    ref[r] = static_cast<float>(acc);
  }

  const VkDeviceSize wBytes = (W.size() + 3) & ~VkDeviceSize(3);
  Buffer bw{}, bx{}, bo{};
  if (!makeBuffer(c, wBytes, bw) || !makeBuffer(c, cols * sizeof(float), bx) ||
      !makeBuffer(c, rows * sizeof(float), bo)) {
    bw.destroy();
    bx.destroy();
    bo.destroy();
    return {true, false, "buffer allocation failed"};
  }
  upload(bw, W.data(), W.size());
  upload(bx, x.data(), cols * sizeof(float));
  struct {
    std::uint32_t rows, cols;
  } pc{static_cast<std::uint32_t>(rows), static_cast<std::uint32_t>(cols)};
  const bool ran = dispatch(c, qmatmul_q8_0_spv, sizeof(qmatmul_q8_0_spv), {bw.buf, bx.buf, bo.buf},
                            &pc, sizeof(pc), (rows + 63) / 64);
  if (ran) download(bo, got.data(), rows * sizeof(float));
  bw.destroy();
  bx.destroy();
  bo.destroy();
  if (!ran) return {true, false, "qmatmul dispatch failed"};

  float maxErr = 0.0f;
  for (int r = 0; r < rows; ++r) maxErr = std::max(maxErr, std::fabs(got[r] - ref[r]));
  if (maxErr > 1e-2f)
    return {true, false, "Vulkan qmatmul disagrees with host reference (max err " +
                             std::to_string(maxErr) + ")"};

  return {true, true, std::string("Vulkan Q8_0 matmul matches host reference (max err ") +
                          std::to_string(maxErr) + ") on " + dp.deviceName};
}

// Shared driver for a K-quant (Q4_K / Q6_K) GEMV self-test: builds a synthetic weight matrix and a
// host reference with `ref`, runs `spirv` on the device, and compares. `blockBytes` is the super-
// block size (144 for Q4_K, 210 for Q6_K), `fill` populates one super-block's bytes given (r, sb).
SelfTestResult kQuantSelfTest(const char* label, const std::uint32_t* spirv, std::size_t spirvBytes,
                              int blockBytes,
                              const std::function<void(int r, int sb, std::uint8_t* blk,
                                                       const std::vector<float>& x, double& acc)>& fill) {
  Context c = makeContext();
  if (!c.ok) return {false, false, "no Vulkan device present"};
  VkPhysicalDeviceProperties dp{};
  vkGetPhysicalDeviceProperties(c.phys, &dp);

  const int rows = 48, cols = 512;  // 2 super-blocks/row
  const int nSB = cols / 256;
  const std::size_t rowBytes = static_cast<std::size_t>(nSB) * blockBytes;
  std::vector<std::uint8_t> W(static_cast<std::size_t>(rows) * rowBytes, 0);
  std::vector<float> x(cols), ref(rows, 0.0f), got(rows, 0.0f);
  for (int i = 0; i < cols; ++i) x[i] = 0.05f * ((i % 13) - 6);
  for (int r = 0; r < rows; ++r) {
    double acc = 0.0;
    for (int sb = 0; sb < nSB; ++sb) {
      std::uint8_t* blk = W.data() + static_cast<std::size_t>(r) * rowBytes +
                          static_cast<std::size_t>(sb) * blockBytes;
      fill(r, sb, blk, x, acc);
    }
    ref[r] = static_cast<float>(acc);
  }

  const VkDeviceSize wBytes = (W.size() + 3) & ~VkDeviceSize(3);
  Buffer bw{}, bx{}, bo{};
  if (!makeBuffer(c, wBytes, bw) || !makeBuffer(c, cols * sizeof(float), bx) ||
      !makeBuffer(c, rows * sizeof(float), bo)) {
    bw.destroy();
    bx.destroy();
    bo.destroy();
    return {true, false, "buffer allocation failed"};
  }
  upload(bw, W.data(), W.size());
  upload(bx, x.data(), cols * sizeof(float));
  struct {
    std::uint32_t rows, cols;
  } pc{static_cast<std::uint32_t>(rows), static_cast<std::uint32_t>(cols)};
  const bool ran =
      dispatch(c, spirv, spirvBytes, {bw.buf, bx.buf, bo.buf}, &pc, sizeof(pc), (rows + 63) / 64);
  if (ran) download(bo, got.data(), rows * sizeof(float));
  bw.destroy();
  bx.destroy();
  bo.destroy();
  if (!ran) return {true, false, std::string(label) + " dispatch failed"};

  float maxErr = 0.0f, ref2 = 0.0f;
  for (int r = 0; r < rows; ++r) {
    maxErr = std::max(maxErr, std::fabs(got[r] - ref[r]));
    ref2 = std::max(ref2, std::fabs(ref[r]));
  }
  const float tol = 1e-2f * (1.0f + ref2);  // scale tolerance to the magnitude of the reference
  if (maxErr > tol)
    return {true, false, std::string(label) + " disagrees with host reference (max err " +
                             std::to_string(maxErr) + ")"};
  return {true, true, std::string(label) + " matches host reference (max err " +
                          std::to_string(maxErr) + ") on " + dp.deviceName};
}

SelfTestResult qmatmulQ4_KSelfTest() {
  return kQuantSelfTest(
      "Vulkan Q4_K matmul", qmatmul_q4_k_spv, sizeof(qmatmul_q4_k_spv), 144,
      [](int r, int sb, std::uint8_t* blk, const std::vector<float>& x, double& acc) {
        const std::uint16_t dh = encodeHalf(0.015f * ((r % 5) + 1));
        const std::uint16_t mh = encodeHalf(0.007f * ((sb % 3) + 1));
        blk[0] = dh & 0xFF;
        blk[1] = dh >> 8;
        blk[2] = mh & 0xFF;
        blk[3] = mh >> 8;
        for (int i = 0; i < 12; ++i) blk[4 + i] = static_cast<std::uint8_t>((r * 7 + sb * 3 + i * 11) & 0x3F);
        std::uint8_t* qs = blk + 16;
        for (int i = 0; i < 128; ++i) qs[i] = static_cast<std::uint8_t>((r + sb + i * 5) & 0xFF);
        const float d = decodeHalf(dh), dmin = decodeHalf(mh);
        for (int j = 0; j < 8; ++j) {
          unsigned char sc, m;
          getScaleMinK4(j, blk + 4, sc, m);
          for (int t = 0; t < 32; ++t) {
            const int i = j * 32 + t;
            const int chunk = i / 64, local = i % 64;
            const std::uint8_t qbyte = qs[chunk * 32 + (local & 31)];
            const int nib = (local < 32) ? (qbyte & 0xF) : (qbyte >> 4);
            acc += (d * sc * nib - dmin * m) * x[static_cast<std::size_t>(sb) * 256 + i];
          }
        }
      });
}

SelfTestResult qmatmulQ6_KSelfTest() {
  return kQuantSelfTest(
      "Vulkan Q6_K matmul", qmatmul_q6_k_spv, sizeof(qmatmul_q6_k_spv), 210,
      [](int r, int sb, std::uint8_t* blk, const std::vector<float>& x, double& acc) {
        std::uint8_t* ql = blk;
        std::uint8_t* qh = blk + 128;
        signed char* sc = reinterpret_cast<signed char*>(blk + 192);
        for (int i = 0; i < 128; ++i) ql[i] = static_cast<std::uint8_t>((r + sb + i * 3) & 0xFF);
        for (int i = 0; i < 64; ++i) qh[i] = static_cast<std::uint8_t>((r * 2 + sb + i * 7) & 0xFF);
        for (int i = 0; i < 16; ++i) sc[i] = static_cast<signed char>(((r + sb + i * 5) % 25) - 12);
        const std::uint16_t dh = encodeHalf(0.012f * ((r % 6) + 1));
        blk[208] = dh & 0xFF;
        blk[209] = dh >> 8;
        const float d = decodeHalf(dh);
        for (int i = 0; i < 256; ++i) {
          const int hlf = i >> 7, p = i & 127, l = p & 31, quarter = p >> 5, isub = l >> 4;
          const std::uint8_t* qlh = ql + hlf * 64;
          const std::uint8_t* qhh = qh + hlf * 32;
          int lo, hi;
          if (quarter == 0) { lo = qlh[l] & 0xF;      hi = (qhh[l] >> 0) & 3; }
          else if (quarter == 1) { lo = qlh[l + 32] & 0xF; hi = (qhh[l] >> 2) & 3; }
          else if (quarter == 2) { lo = qlh[l] >> 4;   hi = (qhh[l] >> 4) & 3; }
          else { lo = qlh[l + 32] >> 4;                hi = (qhh[l] >> 6) & 3; }
          const int q = (lo | (hi << 4)) - 32;
          const int scv = sc[hlf * 8 + isub + quarter * 2];
          acc += d * scv * q * x[static_cast<std::size_t>(sb) * 256 + i];
        }
      });
}

SelfTestResult opsSelfTest() {
  Context c = makeContext();
  if (!c.ok) return {false, false, "no Vulkan device present"};
  VkPhysicalDeviceProperties dp{};
  vkGetPhysicalDeviceProperties(c.phys, &dp);

  float maxErr = 0.0f;
  auto track = [&](const std::vector<float>& a, const std::vector<float>& b) {
    for (std::size_t i = 0; i < a.size(); ++i) maxErr = std::max(maxErr, std::fabs(a[i] - b[i]));
  };
  const char* failed = nullptr;

  // RMSNorm: bindings {out, x, w}, one workgroup.
  {
    const int n = 512;
    std::vector<float> x(n), w(n), ref(n), got(n);
    for (int i = 0; i < n; ++i) {
      x[i] = 0.01f * ((i % 13) - 6);
      w[i] = 0.5f + 0.001f * i;
    }
    double sq = 0.0;
    for (float v : x) sq += static_cast<double>(v) * v;
    const float scale = 1.0f / std::sqrt(static_cast<float>(sq / n) + 1e-5f);
    for (int i = 0; i < n; ++i) ref[i] = x[i] * scale * w[i];
    Buffer bo{}, bx{}, bw{};
    if (makeBuffer(c, n * sizeof(float), bo) && makeBuffer(c, n * sizeof(float), bx) &&
        makeBuffer(c, n * sizeof(float), bw)) {
      upload(bx, x.data(), n * sizeof(float));
      upload(bw, w.data(), n * sizeof(float));
      struct {
        std::uint32_t n;
        float eps;
      } pc{static_cast<std::uint32_t>(n), 1e-5f};
      if (dispatch(c, rmsnorm_spv, sizeof(rmsnorm_spv), {bo.buf, bx.buf, bw.buf}, &pc, sizeof(pc), 1)) {
        download(bo, got.data(), n * sizeof(float));
        track(ref, got);
      } else {
        failed = "rmsnorm";
      }
    } else {
      failed = "rmsnorm alloc";
    }
    bo.destroy();
    bx.destroy();
    bw.destroy();
  }

  // RoPE (NeoX): binding {v} in place.
  if (!failed) {
    const int nH = 4, hd = 8, half = hd / 2, pos = 3, n = nH * hd;
    const float base = 10000.0f;
    std::vector<float> v(n), ref(n), got(n);
    for (int i = 0; i < n; ++i) v[i] = 0.1f * ((i % 7) - 3);
    ref = v;
    for (int h = 0; h < nH; ++h)
      for (int i = 0; i < half; ++i) {
        const float theta = pos * std::pow(base, -2.0f * i / hd);
        const float cc = std::cos(theta), ss = std::sin(theta);
        const float a = ref[h * hd + i], b = ref[h * hd + i + half];
        ref[h * hd + i] = a * cc - b * ss;
        ref[h * hd + i + half] = a * ss + b * cc;
      }
    Buffer bv{};
    if (makeBuffer(c, n * sizeof(float), bv)) {
      upload(bv, v.data(), n * sizeof(float));
      struct {
        std::uint32_t nHeads, headDim;
        std::int32_t pos;
        float freqBase;
      } pc{static_cast<std::uint32_t>(nH), static_cast<std::uint32_t>(hd), pos, base};
      if (dispatch(c, rope_spv, sizeof(rope_spv), {bv.buf}, &pc, sizeof(pc),
                   static_cast<std::uint32_t>((nH * half + 63) / 64))) {
        download(bv, got.data(), n * sizeof(float));
        track(ref, got);
      } else {
        failed = "rope";
      }
    } else {
      failed = "rope alloc";
    }
    bv.destroy();
  }

  // SwiGLU: bindings {out, gate, up}.
  if (!failed) {
    const int n = 1000;
    std::vector<float> g(n), u(n), ref(n), got(n);
    for (int i = 0; i < n; ++i) {
      g[i] = 0.02f * ((i % 11) - 5);
      u[i] = 0.03f * ((i % 9) - 4);
      ref[i] = (g[i] / (1.0f + std::exp(-g[i]))) * u[i];
    }
    Buffer bo{}, bg{}, bu{};
    if (makeBuffer(c, n * sizeof(float), bo) && makeBuffer(c, n * sizeof(float), bg) &&
        makeBuffer(c, n * sizeof(float), bu)) {
      upload(bg, g.data(), n * sizeof(float));
      upload(bu, u.data(), n * sizeof(float));
      struct {
        std::uint32_t n;
      } pc{static_cast<std::uint32_t>(n)};
      if (dispatch(c, swiglu_spv, sizeof(swiglu_spv), {bo.buf, bg.buf, bu.buf}, &pc, sizeof(pc),
                   static_cast<std::uint32_t>((n + 255) / 256))) {
        download(bo, got.data(), n * sizeof(float));
        track(ref, got);
      } else {
        failed = "swiglu";
      }
    } else {
      failed = "swiglu alloc";
    }
    bo.destroy();
    bg.destroy();
    bu.destroy();
  }

  // Residual add: binding {out(=a, in place), x(=b)}.
  if (!failed) {
    const int n = 1000;
    std::vector<float> a(n), b(n), ref(n), got(n);
    for (int i = 0; i < n; ++i) {
      a[i] = 0.1f * i;
      b[i] = -0.05f * i;
      ref[i] = a[i] + b[i];
    }
    Buffer ba{}, bb{};
    if (makeBuffer(c, n * sizeof(float), ba) && makeBuffer(c, n * sizeof(float), bb)) {
      upload(ba, a.data(), n * sizeof(float));
      upload(bb, b.data(), n * sizeof(float));
      struct {
        std::uint32_t n;
      } pc{static_cast<std::uint32_t>(n)};
      if (dispatch(c, add_spv, sizeof(add_spv), {ba.buf, bb.buf}, &pc, sizeof(pc),
                   static_cast<std::uint32_t>((n + 255) / 256))) {
        download(ba, got.data(), n * sizeof(float));
        track(ref, got);
      } else {
        failed = "add";
      }
    } else {
      failed = "add alloc";
    }
    ba.destroy();
    bb.destroy();
  }

  if (failed) return {true, false, std::string(failed) + " dispatch failed"};
  const bool ok = maxErr < 1e-3f;
  return {true, ok,
          (ok ? "rmsnorm/rope/swiglu/add match CPU (max err " : "Vulkan ops disagree with CPU (max err ") +
              std::to_string(maxErr) + ") on " + dp.deviceName};
}

SelfTestResult attentionSelfTest() {
  Context c = makeContext();
  if (!c.ok) return {false, false, "no Vulkan device present"};
  VkPhysicalDeviceProperties dp{};
  vkGetPhysicalDeviceProperties(c.phys, &dp);

  // GQA: 4 query heads, 2 kv heads, head_dim 8, 5 cached positions (matches the CUDA self-test).
  const int nHeads = 4, nKv = 2, headDim = 8, seqLen = 5;
  const int kvDim = nKv * headDim;
  const int group = nHeads / nKv;
  std::vector<float> q(static_cast<std::size_t>(nHeads) * headDim);
  std::vector<float> K(static_cast<std::size_t>(seqLen) * kvDim);
  std::vector<float> V(static_cast<std::size_t>(seqLen) * kvDim);
  for (std::size_t i = 0; i < q.size(); ++i) q[i] = 0.05f * ((i % 11) - 5);
  for (std::size_t i = 0; i < K.size(); ++i) K[i] = 0.03f * ((i % 13) - 6);
  for (std::size_t i = 0; i < V.size(); ++i) V[i] = 0.04f * ((i % 7) - 3);

  std::vector<float> ref(static_cast<std::size_t>(nHeads) * headDim, 0.0f), got(ref.size());
  const float invSqrt = 1.0f / std::sqrt(static_cast<float>(headDim));
  for (int h = 0; h < nHeads; ++h) {
    const int kvHead = h / group;
    std::vector<float> sc(seqLen);
    for (int t = 0; t < seqLen; ++t) {
      float dot = 0.0f;
      for (int d = 0; d < headDim; ++d)
        dot += q[h * headDim + d] * K[t * kvDim + kvHead * headDim + d];
      sc[t] = dot * invSqrt;
    }
    float mx = sc[0];
    for (int t = 1; t < seqLen; ++t) mx = std::max(mx, sc[t]);
    float sum = 0.0f;
    for (int t = 0; t < seqLen; ++t) {
      sc[t] = std::exp(sc[t] - mx);
      sum += sc[t];
    }
    for (int d = 0; d < headDim; ++d) {
      float acc = 0.0f;
      for (int t = 0; t < seqLen; ++t)
        acc += (sc[t] / sum) * V[t * kvDim + kvHead * headDim + d];
      ref[h * headDim + d] = acc;
    }
  }

  Buffer bo{}, bq{}, bk{}, bv{};
  if (!makeBuffer(c, got.size() * sizeof(float), bo) || !makeBuffer(c, q.size() * sizeof(float), bq) ||
      !makeBuffer(c, K.size() * sizeof(float), bk) || !makeBuffer(c, V.size() * sizeof(float), bv)) {
    bo.destroy();
    bq.destroy();
    bk.destroy();
    bv.destroy();
    return {true, false, "buffer allocation failed"};
  }
  upload(bq, q.data(), q.size() * sizeof(float));
  upload(bk, K.data(), K.size() * sizeof(float));
  upload(bv, V.data(), V.size() * sizeof(float));
  struct {
    std::uint32_t nHeads, nKv, headDim, seqLen, kvDim;
  } pc{static_cast<std::uint32_t>(nHeads), static_cast<std::uint32_t>(nKv),
       static_cast<std::uint32_t>(headDim), static_cast<std::uint32_t>(seqLen),
       static_cast<std::uint32_t>(kvDim)};
  const bool ran = dispatch(c, attention_spv, sizeof(attention_spv), {bo.buf, bq.buf, bk.buf, bv.buf},
                            &pc, sizeof(pc), static_cast<std::uint32_t>(nHeads));
  if (ran) download(bo, got.data(), got.size() * sizeof(float));
  bo.destroy();
  bq.destroy();
  bk.destroy();
  bv.destroy();
  if (!ran) return {true, false, "attention dispatch failed"};

  float maxErr = 0.0f;
  for (std::size_t i = 0; i < ref.size(); ++i) maxErr = std::max(maxErr, std::fabs(got[i] - ref[i]));
  const bool ok = maxErr < 1e-3f;
  return {true, ok,
          (ok ? "GQA decode attention matches CPU (max err " : "attention disagrees with CPU (max err ") +
              std::to_string(maxErr) + ") on " + dp.deviceName};
}

